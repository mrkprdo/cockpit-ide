const path = require('path');
const fs = require('fs');
const crypto = require('crypto');

function generateHash() {
  const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'package.json'), 'utf-8'));
  const appVersion = pkg.version;
  const specgenPath = path.join(__dirname, '..', 'SPECGEN.md');
  const specgenContent = fs.readFileSync(specgenPath, 'utf-8');
  const specgenHash = crypto.createHash('sha256').update(`${appVersion}:${specgenContent}`).digest('hex');
  const hashFile = path.join(__dirname, '..', 'src', 'renderer', 'specgen-hash.ts');
  fs.writeFileSync(
    hashFile,
    `// Auto-generated by build-renderer.js — do not edit manually.\n` +
    `// Regenerated on every \`npm run build\`. Commit this file.\n` +
    `export const SPECGEN_HASH = '${specgenHash}';\n` +
    `export const SPECGEN_VERSION = '${appVersion}';\n`,
  );
}

if (require.main === module) generateHash();
module.exports = generateHash;
