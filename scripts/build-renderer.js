const path = require('path');
const fs = require('fs');
const crypto = require('crypto');
const esbuild = require('esbuild');

// Always wipe and re-copy dist/vs — avoids stale files from old Monaco versions
const vsDir = path.join(__dirname, '..', 'dist', 'vs');
const vsSrc = path.join(__dirname, '..', 'node_modules', 'monaco-editor', 'min', 'vs');
if (fs.existsSync(vsDir)) fs.rmSync(vsDir, { recursive: true, force: true });
fs.cpSync(vsSrc, vsDir, { recursive: true });

// Hash SPECGEN.md seeded with app version so the bundle can verify workspace
// copies haven't drifted from the bundled template.
const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'package.json'), 'utf-8'));
const appVersion = pkg.version;
const specgenPath = path.join(__dirname, '..', 'SPECGEN.md');
const specgenContent = fs.readFileSync(specgenPath, 'utf-8');
const specgenHash = crypto.createHash('sha256').update(`${appVersion}:${specgenContent}`).digest('hex');
const hashFile = path.join(__dirname, '..', 'src', 'renderer', 'specgen-hash.ts');
fs.writeFileSync(
  hashFile,
  `// Auto-generated by build-renderer.js — do not edit manually.\n` +
  `// Regenerated on every \`npm run build\`. Commit this file.\n` +
  `export const SPECGEN_HASH = '${specgenHash}';\n` +
  `export const SPECGEN_VERSION = '${appVersion}';\n`,
);

const isProd = process.env.NODE_ENV === 'production';

esbuild.buildSync({
  entryPoints: ['src/renderer/index.ts'],
  bundle: true,
  outfile: 'dist/renderer/index.js',
  format: 'iife',
  minify: isProd,
  sourcemap: !isProd,
  loader: { '.md': 'text' },
  define: {
    'process.env.NODE_ENV': isProd ? '"production"' : '"development"',
  },
});
